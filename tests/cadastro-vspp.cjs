const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const nodes = new Map();
const node = () => ({ value: '', textContent: '', children: [], append(...n) { this.children.push(...n); }, replaceChildren(...n) { this.children = n; }, addEventListener() {}, setAttribute() {}, add(n) { this.children.push(n); }, dataset: {} });
const document = { querySelector(s) { if (!nodes.has(s)) nodes.set(s,node()); return nodes.get(s); }, createElement: node };
const data = new Map();
const context = { document, console, structuredClone, localStorage: {getItem:k=>data.get(k)??null,setItem:(k,v)=>data.set(k,v)}, addEventListener() {} };
context.window = context; vm.createContext(context);
for (const name of ['operacao','vspp-exemplos']) vm.runInContext(fs.readFileSync(path.join(__dirname,'../js',name+'.js'),'utf8'),context);
const registryCode = fs.readFileSync(path.join(__dirname,'../js/cadastro-vspp.js'),'utf8');
vm.runInContext(registryCode,context);
document.querySelector('#vspp-filter').value = 'active';
context.VSPPRegistry.render();
assert.equal(document.querySelector('#vspp-count').textContent,'0 profissional(is) encontrado(s)','fresh registry must be empty');
const imported = context.VSPPExamples.map((fields,i)=>({id:`demo-vspp-${i+1}`,fields:{...fields},demo:false}));
data.set('apeVsppRegistryV1',JSON.stringify([...imported,{id:'demo-vspp-1',fields:context.VSPPExamples[0],demo:true}]));
vm.runInContext(registryCode,context);
assert.equal(JSON.parse(data.get('apeVsppRegistryV1')).length,30,'only bundled demo records are removed');
vm.runInContext(fs.readFileSync(path.join(__dirname,'../js/equipe-transporte.js'),'utf8'),context);
const R = context.VSPPRegistry;
assert.equal(context.VSPPExamples.length,30);
const record = {id:'demo-vspp-1',fields:context.VSPPExamples[0],photo:''};
const copy = R.snapshot(record);
assert.equal(copy.name,record.fields.NOME);
assert.equal(copy.gender,'Não informado');
assert.equal(R.snapshot({...record,fields:{...record.fields,RG:'RG de teste'}}).rg,'RG de teste');
assert.equal(R.snapshot({id:'legacy',fields:{}}).rg,'');
assert(R.isDemo(copy));
assert(!R.isDemo({...copy,registryId:'other'}));
assert(!R.isDemo({...copy,cpf:'111.111.111-11'}));
assert.equal(R.snapshot({...record,photo:'https://example.com/photo.jpg'}).photo,'');
const oldName = copy.name;
record.fields.NOME = 'Nome alterado';
assert.equal(copy.name,oldName,'snapshot must not track registry changes');
record.fields.NOME = oldName;
const car = {type:'car',plate:'ABC1D23',brand:'Teste',model:'Modelo',color:'Azul',year:'2026'};
assert.equal(context.OperationRepeater.validate([copy],[car]),'');
assert.match(context.OperationRepeater.validate([{...copy,registryId:''}],[car]),/CPF/);
assert.match(context.OperationRepeater.validate([copy,copy],[car]),/já foi cadastrado/);
document.querySelector('#vspp-filter').value = 'active';
R.render();
assert.equal(document.querySelector('#vspp-cards').children.length,30);
document.querySelector('#vspp-search').value = '9000000';
R.render();
assert.equal(document.querySelector('#vspp-cards').children.length,1);
assert.equal(JSON.parse(data.get('apeVsppRegistryV1')).length,30);
console.log('Cadastro VSPP: snapshot, busca, fotos e validação de equipe aprovados.');
context.confirm = () => true;
context.crypto = { randomUUID: () => 'test-id' };
(async () => {
  const runImport = async (rows) => document.querySelector('#vspp-import-file').onchange({target:{files:[{size:100,text:async()=>JSON.stringify(rows)}],value:'test'}});
  await runImport([{...context.VSPPExamples[0],EMPRESA:'Empresa de teste'}]);
  const saved = JSON.parse(data.get('apeVsppRegistryV1'));
  assert.equal(saved.length,30,'import must update the matching profile');
  assert.equal(saved[0].fields.EMPRESA,'Empresa de teste');
  const before = data.get('apeVsppRegistryV1');
  await runImport([context.VSPPExamples[0], {RE:'invalid-test',NOME:'Teste pendente',CPF:'111.111.111-11'}]);
  assert.match(document.querySelector('#vspp-message').textContent,/1 cadastros importados/);
  assert.match(document.querySelector('#vspp-message').textContent,/Registro 2: confira o CPF/);
  await runImport([context.VSPPExamples[0],context.VSPPExamples[0]]);
  assert.equal(data.get('apeVsppRegistryV1'),before,'duplicates must not partially write');
  context.localStorage.setItem = () => { throw new Error('Armazenamento indisponível'); };
  await runImport([{...context.VSPPExamples[0],EMPRESA:'Não gravar'}]);
  assert.equal(data.get('apeVsppRegistryV1'),before,'failed save preserves existing data');
  document.querySelector('#vspp-search').value = '';
  R.render();
  let remove = document.querySelector('#vspp-cards').children[0].children[2].children[1];
  remove.onclick();
  assert.equal(data.get('apeVsppRegistryV1'),before,'failed delete preserves data');
  context.localStorage.setItem = (k,v)=>data.set(k,v);
  context.confirm = () => false;
  remove.onclick();
  assert.equal(data.get('apeVsppRegistryV1'),before,'cancelled delete preserves data');
  context.confirm = () => true;
  data.set('superAgendaPrototypeV2','existing agendas');
  remove.onclick();
  assert.equal(JSON.parse(data.get('apeVsppRegistryV1')).length,29);
  assert.equal(data.get('superAgendaPrototypeV2'),'existing agendas');
  console.log('Importação: atualização por RE/CPF, duplicidades e falha de gravação aprovadas.');
})().catch((err) => { console.error(err); process.exitCode=1; });
